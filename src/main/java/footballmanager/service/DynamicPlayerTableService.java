package footballmanager.service;

import footballmanager.service.dto.DynamicPlayerDTO;
import jakarta.persistence.EntityManager;
import jakarta.persistence.PersistenceContext;
import java.math.BigDecimal;
import java.sql.Date;
import java.time.LocalDate;
import java.util.List;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

@Service
public class DynamicPlayerTableService {

    @PersistenceContext
    private EntityManager entityManager;

    private static final Logger log = LoggerFactory.getLogger(DynamicPlayerTableService.class);

    private String tableName(Long teamId) {
        if (teamId == null || teamId <= 0) {
            throw new IllegalArgumentException("Invalid team ID");
        }

        return "players_team_" + teamId;
    }

    @Transactional
    public void createTableForTeam(Long teamId) {
        String table = tableName(teamId);

        String sql = """
        CREATE TABLE IF NOT EXISTS %s (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            first_name VARCHAR(100) NOT NULL,
            last_name VARCHAR(100) NOT NULL,
            birth_date DATE NOT NULL,
            nationality VARCHAR(100) NOT NULL,
            position VARCHAR(50) NOT NULL,
            market_value NUMERIC(21, 2)
        )
        """.formatted(table);

        entityManager.createNativeQuery(sql).executeUpdate();
    }

    @Transactional
    public DynamicPlayerDTO addPlayer(Long teamId, DynamicPlayerDTO player) {
        String table = tableName(teamId);

        String sql = """
        INSERT INTO %s (
            first_name,
            last_name,
            birth_date,
            nationality,
            position,
            market_value
        )
        VALUES (
            :firstName,
            :lastName,
            :birthDate,
            :nationality,
            :position,
            :marketValue
        )
        RETURNING id
        """.formatted(table);

        Object result = entityManager
            .createNativeQuery(sql)
            .setParameter("firstName", player.firstName())
            .setParameter("lastName", player.lastName())
            .setParameter("birthDate", player.birthDate())
            .setParameter("nationality", player.nationality())
            .setParameter("position", player.position())
            .setParameter("marketValue", player.marketValue())
            .getSingleResult();

        Long id = ((Number) result).longValue();

        return new DynamicPlayerDTO(
            id,
            player.firstName(),
            player.lastName(),
            player.birthDate(),
            player.nationality(),
            player.position(),
            player.marketValue()
        );
    }

    @Transactional(readOnly = true)
    public List<DynamicPlayerDTO> getPlayers(Long teamId) {
        long start = System.nanoTime();
        String table = tableName(teamId);

        String sql = """
        SELECT id, first_name, last_name, birth_date,
               nationality, position, market_value
        FROM %s
        ORDER BY id
        """.formatted(table);

        @SuppressWarnings("unchecked")
        List<Object[]> rows = entityManager.createNativeQuery(sql).getResultList();

        long elapsedMs = (System.nanoTime() - start) / 1_000_000;

        log.info("Read players by team: teamId={}, count={}, elapsed={} ms", teamId, rows.size(), elapsedMs);

        return rows.stream().map(this::toDTO).toList();
    }

    @Transactional(readOnly = true)
    public DynamicPlayerDTO getPlayer(Long teamId, Long playerId) {
        String table = tableName(teamId);

        String sql = """
        SELECT id, first_name, last_name, birth_date,
               nationality, position, market_value
        FROM %s
        WHERE id = :playerId
        """.formatted(table);

        @SuppressWarnings("unchecked")
        List<Object[]> rows = entityManager.createNativeQuery(sql).setParameter("playerId", playerId).getResultList();

        if (rows.isEmpty()) {
            throw new jakarta.persistence.EntityNotFoundException("Player not found: " + playerId);
        }

        return toDTO(rows.get(0));
    }

    @Transactional
    public void deletePlayer(Long teamId, Long playerId) {
        String table = tableName(teamId);

        int deleted = entityManager
            .createNativeQuery("DELETE FROM " + table + " WHERE id = :playerId")
            .setParameter("playerId", playerId)
            .executeUpdate();

        if (deleted == 0) {
            throw new jakarta.persistence.EntityNotFoundException("Player not found: " + playerId);
        }
    }

    private DynamicPlayerDTO toDTO(Object[] row) {
        LocalDate birthDate = row[3] instanceof Date date ? date.toLocalDate() : (LocalDate) row[3];

        return new DynamicPlayerDTO(
            ((Number) row[0]).longValue(),
            (String) row[1],
            (String) row[2],
            birthDate,
            (String) row[4],
            (String) row[5],
            (BigDecimal) row[6]
        );
    }
}
